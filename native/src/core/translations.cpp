// ─────────────────────────────────────────────────────────────────────────────
// glt/core/translations.cpp — the embedded translation tables. PURE DATA.
//
// FORMAT: one shared key list (kKeys — the exact English UI strings, the tr()
// lookup keys) plus one positional value array per language. Line N of a
// language array translates line N of kKeys; an empty string means "not
// translated — fall back to English" (the i18n.hpp contract). Rules:
//
//   * kKeys entries MUST stay byte-identical to the source literals. A
//     reworded English string must be reworded here in the same change, or
//     its translations silently drop to English. The canonical list is
//     extractable by scanning tr("...") literals across native/src.
//   * static_assert pins every array to kKeyCount — a forgotten entry is a
//     compile error, never a shifted row. Adding a new UI string that needs
//     translation: add it to kKeys and append one value per language.
//   * Non-ASCII is emitted as \xNN UTF-8 escapes so this file is kept as raw UTF-8 (the build compiles with /utf-8);
//   * Interpolated strings keep their %s / %d placeholders, in the same order.
//
// v1 coverage: ar is complete (including the long help paragraphs); es/pt
// translate everything except a few longest paragraphs; id/ru/tr/vi cover
// the short UI strings and fall back to English for the long ones.
//
// This file intentionally has no logic: only data and the entries() hook.
// ─────────────────────────────────────────────────────────────────────────────
